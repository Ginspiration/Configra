const translations: Record<Language, Record<TranslationKey, string>> = { en, zh };

type Vars = Record<string, string | number>;

export type Translator = (key: TranslationKey, vars?: Vars) => string;

export const languageLabels: Record<Language, string> = {
  zh: '中文',
  en: 'English',
};

export function translate(language: Language, key: TranslationKey, vars: Vars = {}) {
  return translations[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? '' : String(vars[name]),
  );
}
